-- نظام الحضور على Supabase: نفس جداول بلجن st-mina-attendance (نسخة الجداول 8) بنفس القيود.
-- الفروق عن MySQL:
-- - الأوقات timestamptz (وقت عالمي)، واليوم المحلي بيتحسب بتوقيت القاهرة (cairo_today تحت).
-- - الأرقام identity "by default" علشان نقل البيانات يحتفظ بأرقام WordPress القديمة.
-- - foreign keys بحذف متسلسل بدل الحذف اليدوي في PHP.
-- - مستخدمي WordPress (الخدام) بقوا جدول staff بدخول خاص بينا (bcrypt من pgcrypto وcookie موقّعة)، ورقم 0 ("النظام") بقى null.
-- - كل الجداول مقفولة بـ RLS من غير policies: المتصفح مايقدرش يقرا أو يكتب، ودوال السيرفر (service role) بس.

-- تشفير كلمات السر والأرقام السرية (crypt وgen_salt). في Supabase بتبقى في schema اسمها extensions
create extension if not exists pgcrypto with schema extensions;

create table services (
  id bigint generated by default as identity primary key,
  slug varchar(64) not null unique,
  name varchar(191) not null,
  is_hidden boolean not null default false,
  created_at timestamptz not null default now()
);

-- الخدام (كانوا مستخدمين WordPress بصلاحية stmina_attend). الرقم بيفضل رقم WordPress القديم
create table staff (
  id bigint generated by default as identity primary key,
  display_name varchar(191) not null,
  phone varchar(20) unique,
  email varchar(191) unique,
  password_hash text,                        -- bcrypt من pgcrypto. فاضي لحد ما الدعوة تتقبل
  token_version int not null default 1,      -- بيزيد مع سحب الصلاحية أو تغيير كلمة السر، فكل الجلسات القديمة تبطل
  is_admin boolean not null default false,  -- manage_options: إضافة وإلغاء الخدام
  is_test boolean not null default false,   -- حساب الاختبارات: مستخبي ومايتلغيش
  active boolean not null default true,     -- false بعد إلغاء الصلاحية
  invite_hash text,                          -- sha256 لكود الدعوة، والكود نفسه مابيتخزنش
  invite_expires_at timestamptz,
  created_at timestamptz not null default now()
);

create table members (
  id bigint generated by default as identity primary key,
  full_name varchar(191) not null,
  phone varchar(20) not null unique,
  qr_token char(32) not null unique,
  status varchar(10) not null default 'active' check (status in ('active', 'stopped')),
  registered_at timestamptz not null default now(),
  created_by bigint references staff (id) on delete set null,
  updated_at timestamptz not null default now(),
  card_sent_at timestamptz,
  pin_hash text
);
create index members_status on members (status);

create table member_service (
  member_id bigint not null references members (id) on delete cascade,
  service_id bigint not null references services (id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (member_id, service_id)
);
create index member_service_service on member_service (service_id);

create table notes (
  id bigint generated by default as identity primary key,
  member_id bigint not null references members (id) on delete cascade,
  author_id bigint references staff (id) on delete set null,
  body text not null,
  created_at timestamptz not null default now()
);
create index notes_member on notes (member_id);

-- جلسة واحدة لكل خدمة ونوع ويوم
create table sessions (
  id bigint generated by default as identity primary key,
  service_id bigint not null references services (id) on delete cascade,
  kind varchar(16) not null check (kind in ('mass', 'meeting', 'activity', 'service')),
  session_date date not null,
  status varchar(10) not null default 'open' check (status in ('open', 'closed')),
  opened_by bigint references staff (id) on delete set null,
  opened_at timestamptz not null default now(),
  closed_at timestamptz,
  constraint one_per_day unique (service_id, kind, session_date)
);
create index sessions_status on sessions (status);

-- سجل واحد لكل مخدوم في الجلسة. recorded_by = null يعني النظام (الغياب التلقائي)
create table records (
  id bigint generated by default as identity primary key,
  session_id bigint not null references sessions (id) on delete cascade,
  member_id bigint not null references members (id) on delete cascade,
  status varchar(10) not null default 'present' check (status in ('present', 'excused', 'absent')),
  method varchar(10) not null default 'scan' check (method in ('scan', 'manual', 'auto')),
  recorded_by bigint references staff (id) on delete set null,
  recorded_at timestamptz not null default now(),
  updated_by bigint references staff (id) on delete set null,
  updated_at timestamptz,
  constraint one_per_session unique (session_id, member_id)
);
create index records_member on records (member_id);

-- الأكواد القديمة بعد إعادة الإصدار: المسح يقول "الكارت ده ملغي" بدل "مش معروف"
create table revoked (
  token char(32) primary key,
  member_id bigint not null references members (id) on delete cascade,
  revoked_at timestamptz not null default now()
);

-- حدود محاولات الدخول (كانت transients في WordPress): كل محاولة فاشلة سطر، والعدّ في آخر فترة
create table login_attempts (
  id bigint generated by default as identity primary key,
  bucket text not null,  -- مثلًا 'login:ip:<hash>' أو 'mphone:<phone>'
  at timestamptz not null default now()
);
create index login_attempts_bucket on login_attempts (bucket, at);

-- أي دالة هتتعمل بعد كده مابتتشغّلش من المتصفح إلا لو اديناها صلاحية صريحة
-- (Supabase بيدّي anon وauthenticated صلاحية تشغيل الدوال الجديدة تلقائيًا)
alter default privileges in schema public revoke execute on functions from public, anon, authenticated;

-- اليوم الحالي بتوقيت القاهرة (الجلسات والقفل التلقائي بيتحسبوا بيه)
create function cairo_today() returns date language sql stable as $$
  select (now() at time zone 'Africa/Cairo')::date
$$;

-- RLS: مقفول تمامًا قدام anon وauthenticated. دوال Vercel بتستخدم service role ومابتتأثرش
alter table services enable row level security;
alter table staff enable row level security;
alter table members enable row level security;
alter table member_service enable row level security;
alter table notes enable row level security;
alter table sessions enable row level security;
alter table records enable row level security;
alter table revoked enable row level security;
alter table login_attempts enable row level security;

